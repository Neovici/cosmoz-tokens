import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import process from 'node:process';
import { pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';
const { values } = parseArgs({
	options: {
		design: { type: 'string' },
		check: { type: 'boolean', default: false },
	},
});
if (!values.design) throw new Error('Provide --design /path/to/design.');
const { appFoundationCss } = await import(
	pathToFileURL(resolve(values.design, 'scripts/app-foundation.mjs'))
);
const foundation = appFoundationCss();
const names = [...foundation.matchAll(/\t(--[\w-]+):/gu)].map((m) => m[1]);
const files = [
	'primitives',
	'typography',
	'spacing',
	'shadows',
	'semantic',
	'fallback',
	'glass',
	'surface',
	'motion',
	'button-glass',
];
const sources = await Promise.all(
	files.map((name) => readFile(`src/${name}.css`, 'utf8')),
);
const legacy = new Set(sources.join('\n').match(/--cz-[\w-]+(?=:)/gu));
const palette = [...new Set(sources[0].match(/--cz-[\w-]+(?=:)/gu))];
const header =
	'/* Generated by scripts/sync-app-theme.mjs. Public app tokens are unprefixed. */\n';
const extras = [...legacy].filter(
	(name) =>
		name.startsWith('--cz-color-') &&
		!palette.includes(name) &&
		!names.includes(name.replace('--cz-', '--')),
);
const primitives =
	header +
	sources[0].replaceAll('--cz-', '--') +
	'\n:root {\n' +
	extras
		.map((name) => `\t${name.replace('--cz-', '--')}: var(${name});`)
		.join('\n') +
	'\n}\n';
const compatibility =
	header +
	'/* Existing component names remain aliases; no new prefixed API is introduced. */\n:root {\n' +
	[
		...new Set([
			...names,
			...palette.map((name) => name.replace('--cz-', '--')),
		]),
	]
		.filter((name) => legacy.has(name.replace('--', '--cz-')))
		.map((name) => `\t${name.replace('--', '--cz-')}: var(${name});`)
		.join('\n') +
	'\n}\n';
for (const [file, content] of [
	['app-foundation.css', foundation],
	['app-primitives.css', primitives],
	['app-compatibility.css', compatibility],
]) {
	const target = `src/${file}`;
	if (values.check) {
		if (
			(await readFile(target, 'utf8')).replace(/\s/gu, '') !==
			content.replace(/\s/gu, '')
		) {
			throw new Error(`${target} is out of sync.`);
		}
	} else await writeFile(target, content);
}
process.stdout.write(
	values.check
		? 'Shared app theme and compatibility aliases are in sync.\n'
		: 'Updated the shared app theme and compatibility aliases.\n',
);
